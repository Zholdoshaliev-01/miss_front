import { useEffect, useState } from 'react'

export const LANGUAGE_KEY = 'kunduz-study-hub-language'
export const LANGUAGE_EVENT = 'kunduz-study-hub-language-changed'

export const languages = [
  {
    code: 'ky',
    label: 'Кыргызча',
    nativeLabel: 'Кыргызча',
    helper: 'Интерфейстин негизги тили',
  },
  {
    code: 'ru',
    label: 'Русский',
    nativeLabel: 'Русский',
    helper: 'Основной язык интерфейса',
  },
  {
    code: 'en',
    label: 'English',
    nativeLabel: 'English',
    helper: 'Main interface language',
  },
] as const

export type LanguageCode = typeof languages[number]['code']

export function getSavedLanguage(): LanguageCode {
  const saved = localStorage.getItem(LANGUAGE_KEY)
  return languages.some((item) => item.code === saved) ? (saved as LanguageCode) : 'ru'
}

export function saveLanguage(language: LanguageCode) {
  localStorage.setItem(LANGUAGE_KEY, language)
  document.documentElement.lang = language
  window.dispatchEvent(new Event(LANGUAGE_EVENT))
}

export function useLanguage() {
  const [language, setLanguageState] = useState<LanguageCode>(getSavedLanguage)

  useEffect(() => {
    const handleLanguageChange = () => setLanguageState(getSavedLanguage())
    window.addEventListener(LANGUAGE_EVENT, handleLanguageChange)
    window.addEventListener('storage', handleLanguageChange)
    document.documentElement.lang = language
    return () => {
      window.removeEventListener(LANGUAGE_EVENT, handleLanguageChange)
      window.removeEventListener('storage', handleLanguageChange)
    }
  }, [language])

  const setLanguage = (nextLanguage: LanguageCode) => {
    saveLanguage(nextLanguage)
    setLanguageState(nextLanguage)
  }

  return { language, setLanguage }
}

